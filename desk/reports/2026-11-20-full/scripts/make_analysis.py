"""Builds analyse_full.py from the 20 Nov report analysis plus the extra sections, so the shared logic is not
copied by hand. Earlier copper and rotation results are read from inputs/prior_tests.json (so the analysis also
runs on the weekly-desk branch, which has no copper/ or rotation/ folders).

Usage (from desk/): python reports/2026-11-20-full/scripts/make_analysis.py
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
base = (HERE.parents[1] / "2026-11-20" / "scripts" / "analyse_report.py").read_text(encoding="utf-8")
old = ('cop = json.load(open(REPO / "copper" / "reports" / "2026-11-18" / "results.json"))\n'
       'rot = json.load(open(REPO / "rotation" / "reports" / "2026-11-18" / "results.json"))')
new = ('prior = json.load(open(N / "inputs" / "prior_tests.json"))\n'
       'cop = {"preregistered": prior["copper_preregistered"]}\n'
       'rot = {"profit_taking": prior["rotation_profit_taking"], "robustness": prior["rotation_robustness"]}')
assert base.count(old) == 1, "anchor for earlier results not found"
base = base.replace(old, new)
base = base.replace('"copper R² (4 weeks) and profit-taking correlation match the committed results files"',
                    '"copper R² (4 weeks) and profit-taking correlation match the copies in inputs/prior_tests.json"')
base = base.replace('"""20 Nov full report:', '"""20 Nov full analysis (generated by make_analysis.py; do not edit):')
extra = (HERE / "extra_sections.py").read_text(encoding="utf-8")
(HERE / "analyse_full.py").write_text(base + "\n\n" + extra, encoding="utf-8")
print("wrote", HERE / "analyse_full.py")
