"""Builds build_full.py from the 20 Nov report builder plus the new parts (money flows, other markets after past
peaks, a wider summary), so the shared layout code is not copied by hand.

Usage (from desk/): python reports/2026-11-20-full/scripts/make_build.py
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
src = (HERE.parents[1] / "2026-11-20" / "scripts" / "build_report.py").read_text(encoding="utf-8")
part = lambda name: (HERE / name).read_text(encoding="utf-8")  # noqa: E731


def swap(text, old, new):
    assert text.count(old) == 1, f"anchor not found once: {old[:60]}"
    return text.replace(old, new)


src = swap(src, '"""Full report, 20 Nov 2026:', '"""Full analysis, 20 Nov 2026 (generated by make_build.py; do not edit):')
src = swap(src, '"GOLD  |  THE 2026 SELL-OFF"', '"GOLD  |  FULL ANALYSIS"')
src = swap(src, '"Report: what is happening, why, and how it compares with past peaks"',
           '"Gold now, the macro, money flows, and the past peaks compared"')
src = swap(src, 'title="Gold: the 2026 sell-off"', 'title="Gold: full analysis, 20 Nov 2026"')
src = swap(src, '("This week", pc(R["r_week"]), "worst week since at least 2000", RED),',
           '("This week", pc(R["r_week"]), "worst week since at least 2000" if R["n_worse_weeks_since_2000"] == 0 '
           'else f"{R[\'n_worse_weeks_since_2000\']} worse weeks since 2000", RED),')
# charts
src = swap(src, "# ---------------------------------------------------------------- PDF",
           part("part_charts.py") + "# ---------------------------------------------------------------- PDF")
# summary: replace the numbered list
a = src.index('story.append(Paragraph("Summary", S["h1"]))')
b = src.index("story += [Spacer(1, 2), img(c_overview),")
src = src[:a] + part("part_summary.py") + src[b:]
# new money page before the gold-flows page, new peaks page before the tests page
src = swap(src, "# ---------------- page 4: flows and positioning", part("part_money.py") + "# ---------------- page 4: flows and positioning")
src = swap(src, "# ---------------- page 7: tests", part("part_peaks.py") + "# ---------------- page 7: tests")
# renumber the sections that follow
for old, new in (('"3. Money flows and positioning"', '"4. Gold flows and positioning"'),
                 ('"4. What the desk model says"', '"5. What the desk model says"'),
                 ('"5. The past peaks compared"', '"6. The past peaks compared"'),
                 ('"6. What the tests say"', '"8. What the tests say"'),
                 ('"7. What would decide the next move"', '"9. What would decide the next move"')):
    src = swap(src, old, new)
(HERE / "build_full.py").write_text(src, encoding="utf-8")
print("wrote", HERE / "build_full.py")
